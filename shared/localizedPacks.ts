export type SupportedLanguage = 'en' | 'es' | 'fr' | 'de';

export interface LanguageOption {
  code: SupportedLanguage;
  nativeLabel: string;
  englishLabel: string;
  shortCode: string;
}

export const SUPPORTED_LANGUAGES: LanguageOption[] = [
  { code: 'en', nativeLabel: 'English', englishLabel: 'English', shortCode: 'EN' },
  { code: 'es', nativeLabel: 'Español', englishLabel: 'Spanish', shortCode: 'ES' },
  { code: 'fr', nativeLabel: 'Français', englishLabel: 'French', shortCode: 'FR' },
  { code: 'de', nativeLabel: 'Deutsch', englishLabel: 'German', shortCode: 'DE' },
];

export function normalizeLanguage(raw?: string): SupportedLanguage {
  if (raw === 'es' || raw === 'fr' || raw === 'de') return raw;
  return 'en';
}

